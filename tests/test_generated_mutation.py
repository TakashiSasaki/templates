@pytest.mark.parametrize("record_action", ["create", "replace"])
@pytest.mark.parametrize("takeover_mode", ["replace", "same-inode"])
def test_rollback_never_clobbers_a_concurrent_takeover(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    record_action: str,
    takeover_mode: str,
) -> None:
    if record_action == "replace":
        _apply(tmp_path, {"first.md": _write_spec(GENERATED)})
        first_before = GENERATED
        first_write = REPLACEMENT
    else:
        first_before = None
        first_write = GENERATED

    original_install = mutation._native_rename_noreplace
    install_failed = False

    def fail_second_install(
        source_fd: int, source: str, destination_fd: int, destination: str
    ) -> None:
        nonlocal install_failed
        if destination == "second.md" and not install_failed:
            (tmp_path / destination).write_bytes(AUTHORED)
            install_failed = True
        original_install(source_fd, source, destination_fd, destination)

    monkeypatch.setattr(mutation, "_native_rename_noreplace", fail_second_install)
    original_detach = mutation._Transaction._detach_owned_public
    takeover_injected = False

    def take_over_before_rollback(self: mutation._Transaction, record: mutation._Record) -> str:
        nonlocal takeover_injected
        if record.binding.relative == "first.md" and not takeover_injected:
            if takeover_mode == "same-inode":
                (tmp_path / "first.md").write_bytes(AUTHORED)
            else:
                replacement = tmp_path / "first.md.replacement"
                replacement.write_bytes(AUTHORED)
                replacement.replace(tmp_path / "first.md")
            takeover_injected = True
        return original_detach(self, record)

    monkeypatch.setattr(mutation._Transaction, "_detach_owned_public", take_over_before_rollback)

    with pytest.raises(mutation.MutationSafetyError):
        _apply(
            tmp_path,
            {"first.md": _write_spec(first_write), "second.md": _write_spec(GENERATED)},
        )

    assert install_failed and takeover_injected
    assert (tmp_path / "first.md").read_bytes() == AUTHORED
    if first_before is None:
        assert (tmp_path / "second.md").read_bytes() == AUTHORED


