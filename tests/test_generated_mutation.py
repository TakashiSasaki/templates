GENERATED = b"<!-- generated by agent-policy -->\ncontent\n"
REPLACEMENT = b"<!-- generated by agent-policy -->\nreplacement\n"
AUTHORED = b"authored bytes must survive\n"


def _supported() -> bool:
    libc = ctypes.CDLL(None, use_errno=True)
    return (
        hasattr(os, "O_NOFOLLOW")
        and hasattr(os, "O_DIRECTORY")
        and all(operation in os.supports_dir_fd for operation in (os.open, os.mkdir, os.unlink))
        and getattr(libc, "renameat2", None) is not None
    )


pytestmark = pytest.mark.skipif(
    not _supported(),
    reason="generated mutation safety requires descriptor-relative renameat2 support",
)


def _owns_generated(content: bytes) -> bool:
    return content.startswith(b"<!-- generated by agent-policy -->")


def _write_spec(content: bytes) -> mutation.WriteSpec:
    return mutation.WriteSpec(content=content, owns_existing=_owns_generated)


def _delete_spec(content: bytes) -> mutation.DeleteSpec:
    return mutation.DeleteSpec(expected=content, owns_existing=_owns_generated)


def _apply(
    root: Path,
    writes: dict[str, mutation.WriteSpec],
    deletes: dict[str, mutation.DeleteSpec] | None = None,
    *,
    lock: bytes = b"lock\n",
    lock_path: str = ".agent-policy.lock",
) -> None:
    mutation.apply_generated_mutations(
        root,
        writes,
        {} if deletes is None else deletes,
        lock_path=lock_path,
        lock=mutation.WriteSpec(lock, lambda _content: True),
    )


def _holding_directories(root: Path) -> list[Path]:
    return sorted(
        path
        for path in root.iterdir()
        if path.is_dir() and path.name.startswith(".agent-policy-mutation-")
    )


_DESTRUCTIVE_METHODS = {
    "unlink",
    "remove",
    "rmdir",
    "rename",
    "replace",
    "move",
    "rmtree",
}
_DESTRUCTIVE_MODULES = {"os", "shutil"}


def _assert_no_unapproved_destructive_calls(source: str) -> None:
    tree = ast.parse(textwrap.dedent(source))
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        function = node.func
        if isinstance(function, ast.Name) and function.id in _DESTRUCTIVE_METHODS:
            raise AssertionError(f"unapproved destructive call: {function.id}")
        if not isinstance(function, ast.Attribute):
            continue
        if function.attr not in _DESTRUCTIVE_METHODS:
            continue
        value = function.value
        if isinstance(value, ast.Name) and value.id in _DESTRUCTIVE_MODULES:
            raise AssertionError(f"unapproved destructive call: {value.id}.{function.attr}")
        if isinstance(value, ast.Call) and isinstance(value.func, ast.Name):
            if value.func.id == "Path":
                raise AssertionError(f"unapproved Path destructive call: {function.attr}")
        if isinstance(value, (ast.Name, ast.Attribute)):
            raise AssertionError(f"unapproved path-method destructive call: {function.attr}")


