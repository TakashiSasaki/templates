def test_apply_refuses_target_changed_after_plan(tmp_path: Path) -> None:
    target = tmp_path / "generated-docs"
    shutil.copytree(_fixture("generated-docs"), target)
    skill = _load_skill()
    skill.run(target, apply=True)
    _commit_generated_target(target)
    catalog = target / "docs/catalog.json"
    (target / "docs/three.md").write_text("# Three\n", encoding="utf-8")
    catalog.write_text(
        json.dumps(
            {
                "documents": [
                    {"path": "docs/one.md"},
                    {"path": "docs/two.md"},
                    {"path": "docs/three.md"},
                ]
            }
        ),
        encoding="utf-8",
    )
    adapter, _ = skill._load_adapter(target, ".progressive-discovery.json")
    plan = skill._plan(
        target,
        adapter,
        skill._index_paths(target, adapter),
        skill._expected_documents(
            target, adapter, skill._discover_inventory_paths(target, adapter)
        )[0],
        skill._generated_specs(adapter),
        skill._policy_state(skill._yaml_policy(target, ".agent-policy.yml")[0]),
    )
    generated = target / "generated/index.md"
    generated.write_text(
        "<!-- generated by maintain-progressive-discovery -->\n# Changed after plan\n",
        encoding="utf-8",
    )

    applied, blockers = skill._apply(
        target, plan, skill._policy_state(skill._yaml_policy(target, ".agent-policy.yml")[0])
    )

    assert applied == []
    assert blockers and "changed since plan" in blockers[0]


