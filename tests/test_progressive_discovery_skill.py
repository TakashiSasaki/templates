def test_generated_and_retired_targets_cannot_escape_root(tmp_path):
    for mode in ('generated_indexes', 'remove_generated_indexes'):
        for kind in ('absolute', 'parent', 'symlink-parent', 'symlink-target'):
            root = tmp_path / (mode + '-' + kind)
            shutil.copytree(_fixture('simple-docs'), root)
            outside = tmp_path / (mode + '-' + kind + '-outside')
            outside.mkdir()
            sentinel = outside / 'index.md'
            sentinel.write_text('<!-- generated by maintain-progressive-discovery -->\n# Outside\n')
            if kind == 'absolute':
                target = str(sentinel)
            elif kind == 'parent':
                target = '../' + outside.name + '/index.md'
            elif kind == 'symlink-parent':
                (root / 'escape').symlink_to(outside, target_is_directory=True)
                target = 'escape/index.md'
            else:
                (root / 'escaped.md').symlink_to(sentinel)
                target = 'escaped.md'
            adapter_path = root / '.progressive-discovery.json'
            adapter = json.loads(adapter_path.read_text())
            adapter[mode] = {target: {}} if mode == 'generated_indexes' else [target]
            adapter_path.write_text(json.dumps(adapter))
            if mode == 'generated_indexes':
                sentinel.unlink()
            report = _load_skill().run(root, apply=True)
            assert report['result'] == 'AUTHORITY_NEEDED', (mode, kind, report)
            assert report['applied'] == []
            if mode == 'generated_indexes':
                assert not sentinel.exists()
            else:
                assert sentinel.read_text().endswith('# Outside\n')


